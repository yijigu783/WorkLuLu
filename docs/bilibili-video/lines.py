# -*- coding: utf-8 -*-
"""配音台词（唯一来源）+ 时长体检。

为什么单独一个文件而不是塞在 make_voice.py 里：
  台词是要反复改的，改一版就要重新合成一遍听效果。台词和合成逻辑
  分开，改文案时不用冒着动到合成代码的风险。
  make_voice.py 和 probe_voice.py 都 from lines import LINES，
  所以这里改一个字，全链路立刻生效。

【时长模型 —— 注意，不是简单的「字数÷语速」】
  合成音的时长 = 朗读时间 + 标点停顿。一开始只按字数估，结果反复翻车：
  镜头 01 只有 21 个字，实测却要 7.32s（合 2.87 字/秒）；
  镜头 02 有 35 个字，实测 8.88s（3.94 字/秒）。
  差别全在标点上 —— 「这个软件叫工作记录本。」这种短句 + 句号，
  停顿占的比例极大。

  用 9 段实测数据拟合出的公式（RMSE 0.79s，够规划用了）：

      秒数 ≈ 汉字数 / 4.65 + 0.40 × 句读块数

  「句读块」= 按 ，。：；！？—— 切开后非空的段数。
  所以想省时间，删「一个逗号」跟删「两个字」几乎等价 ——
  这是改稿时最容易忽略的一条。

【第一版为什么超了 45%】
  原稿按「感觉」写的，433 字，合成 108.63s。
  现在 334 字，合成 89.75s。差的不是字，是原来那些没必要的短句和逗号。

删字的取舍原则（这个比数字重要）：
  · 留「事实」，删「铺垫」。例：「我跟你讲个事，这个软件它……」→ 直接说功能。
  · 留「具体数字」，删「形容词」。「4 MB」留着，「非常小巧」删掉。
  · 留「操作动作」，删「我的感受」。「Ctrl+V 粘进来」留着，「特别方便」删掉。
  · 每句开头的连接词（另外、然后、其实、就是）先删，不影响语义。
  · 并列举例超过两条就砍到两条 —— 观众不会去数，但时长会。
"""
import re

# 拟合出来的口径，改稿时按它算
CPS = 4.65        # 汉字/秒（纯朗读）
PAUSE = 0.40      # 秒/句读块（标点停顿）

# (镜头名, 台词, 目标秒数)
LINES = [
    ("01-片头",
     "这个软件叫工作记录本。一个 4 MB 的 exe，双击就能用，不用装。",
     6.1),

    ("02-痛点",
     "以前用备忘录记：周五交周报、每月十五号对账，"
     "但找凭证还得翻聊天记录。",
     7.7),

    ("03-主界面",
     "打开就是这样。今天该做的、逾期的、这周完成的，一眼扫完。",
     6.2),

    ("04-周期任务",
     "它跟待办清单不一样。待办是做完就划掉，"
     "这个是给永远做不完的事准备的：周五的周报划掉，下周五它自己回来。",
     11.9),

    ("05-附件留痕",
     "最想说这个。跟对方确认的聊天记录、报价单，"
     "按 Ctrl+V 直接粘进详情，图片、PDF 都能存。"
     "它存在数据库里，备份还是一个文件拷走，截图不会掉。",
     13.4),

    ("06-模板",
     "一件事拆成十几个步骤、每个月走一遍，可以存成模板。"
     "下次选个日期，整套步骤连同截止时间一起铺开，打完勾进度条自己动。",
     13.0),

    ("07-绿色",
     "数据默认存本地，不联网、不上传。也可以放在程序旁边，"
     "整个文件夹拷进 U 盘，换台电脑接着用。",
     10.0),

    ("08-数字",
     "最后几个数字：整个程序 4 MB，没广告、没捆绑、不收费，"
     "代码开源，GitHub 上就能下。一个 exe，双击就跑。",
     9.9),

    ("09-收尾",
     "链接在简介里。你也有周期性的事要记的话，可以试试。",
     5.9),
]



def han_count(text):
    """汉字数：只数中日韩统一表意文字。数字、字母、标点都不算 ——
    「4 MB」念出来比 4 个汉字短得多，算进去反而高估时长。"""
    return len(re.findall(r"[\u4e00-\u9fff]", text))


def block_count(text):
    """句读块数：按标点切开后剩下几段。每段末尾会有一个自然停顿。"""
    return len([b for b in re.split(r"[，。：；！？——]", text) if b.strip()])


def estimate(text):
    """按拟合公式估这段念出来多少秒。"""
    return han_count(text) / CPS + PAUSE * block_count(text)


def stats():
    """改稿时跑的体检。不用另开计算器。"""
    total_h = 0
    total_t = 0.0
    total_target = 0.0
    for name, text, target in LINES:
        h = han_count(text)
        est = estimate(text)
        total_h += h
        total_t += est
        total_target += target
        # 目标 ±1.2s 内算合格。合成音的断句跟公式总有出入，
        # 卡太死会逼着改稿来回横跳，卡太松就失去意义了。
        flag = "OK " if abs(est - target) <= 1.2 else "!! "
        print(f"{flag}{name:<12}{h:>4} 字 / {block_count(text):>2} 块   "
              f"估 {est:>5.2f}s   目标 {target:>4.1f}s   差 {est - target:>+5.2f}s")
    print("-" * 66)
    print(f"  合计 {total_h} 字，估 {total_t:.1f}s   （分镜目标合计 {total_target:.1f}s）")
    # 成片 = 各镜画面时长之和 + 片尾留白。
    # 剪的时候以配音为准去凑画面，所以各镜画面 = 各镜配音。
    # 片尾只加 3s：镜头 01 本身就是展开动画的标题帧，不需要单开黑场起幅；
    # 这 3s 给片尾（logo + 仓库地址），声音停了别立刻黑屏就行。
    # 注：这是写稿时的估算。合成完以 make_voice.py 的实测值为准，
    # 配音 86.3s + 片尾 3s = 89.3s，正好卡在 90s 内。
    runtime = total_t + 3.0
    ok = "OK" if 60 <= runtime <= 90 else "超区间，要调"
    print(f"  成片预估 {runtime:.1f}s（配音 {total_t:.1f}s + 片尾 3s）   {ok}")
    return total_h, total_t


if __name__ == "__main__":
    print(f"时长模型：秒 = 汉字/{CPS} + {PAUSE} × 句读块（由实测数据拟合，RMSE 0.79s）\n")
    stats()

