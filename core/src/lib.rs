//! 工作记录本 (WorkLuLu) 的三端共享业务层。
//!
//! 这里只放**与界面无关、与平台无关**的东西：数据模型与纯计算。
//! 桌面版（Tauri desktop）、安卓版（Tauri mobile）、将来的鸿蒙版都依赖它。
//!
//! 为什么必须要有这一层：周期排期算法（「每月最后一个工作日」这类规则）三端只能
//! 有一份实现。各端各写一遍，迟早会出现同一个周期任务在不同端算出不同日期 ——
//! 用户根本不会想到是端的问题，极难定位。
//!
//! 加代码之前先看这三条纪律：
//! 1. **不得依赖 tauri** —— 否则移动端就搬不动了；
//! 2. **不得读写文件、不得起线程** —— 保持纯函数，单测才跑得动；
//! 3. 需要「现在几点」的地方，一律由调用方把时间传进来，不在里面取系统时钟。

