//! 时间工具。
//!
//! # 为什么这里可以直接取系统时钟
//!
//! `core` 的三条纪律里有一条是「不取系统时钟」，本层破例 —— 这不是疏忽，
//! 是权衡后的选择，理由有两条：
//!
//! 1. **排期算法的正确性依赖参照时刻**，所以 `core` 必须把 `from` 交给调用方，
//!    否则同一份规则在不同时刻跑出不同结果、还没法复现。而数据层的正确性
//!    不依赖「现在几点」—— 它只是给记录盖个时间戳。
//! 2. 把 `now` 一路穿过十来个写函数的签名，收益是「时间戳可断言」，
//!    而现有 130 项测试没有一项断言过具体时间戳（它们断言的是顺序和存在性）。
//!    为一个用不上的收益去改十来个签名，在「零行为变化」的重构里是净风险。
//!
//! 真需要确定性时间的时候，把 `now_local()` 换成入参即可，改动局限在本文件。

use chrono::{DateTime, Local};

/// 本地时区的当前时刻。
pub fn now_local() -> DateTime<Local> {
    Local::now()
}

/// 解析 RFC3339 字符串。库里存的时间一律是 RFC3339。
pub fn parse_dt(s: &str) -> Option<DateTime<Local>> {
    DateTime::parse_from_rfc3339(s).ok().map(|d| d.with_timezone(&Local))
}
